export function Method() {
  return (
    <DocPage title="Метод и ограничения" updated="16 сентября 2026 года">
      <h2>Откуда фото</h2>
      <p>
        Вуз находится в Wikidata, оттуда берутся координаты, город, сайт, названия и категория на Wikimedia Commons. Кандидаты собираются
        параллельно: файлы категории вуза и файлы с геометкой рядом с кампусом на Commons, изображения со страниц официального сайта про
        общежития, кампус, библиотеку, спорт и студенческую жизнь, фото с Flickr под свободными лицензиями, если подключён ключ, и виды
        города вокруг его центра. Граница кампуса и объекты рядом (общежития, корпуса, библиотеки, спортобъекты) берутся из OpenStreetMap.
      </p>
      <h2>Как проверяется принадлежность</h2>
      <p>
        Для каждого фото считаются сигналы: геометка относительно границы кампуса и других вузов рядом, название вуза или его сокращение в
        подписи, описании и категориях, тип источника, сходство с эталонными фото вуза, уверенность классификатора в разделе, признаки мусора и
        водяного знака. Логистическая модель переводит сигналы в достоверность от 0 до 100. От 75 фото считается подтверждённым, от 50
        вероятным, ниже попадает в неподтверждённые и в фонд не входит. Вклад каждого сигнала виден в карточке.
      </p>
      <h2>Модели</h2>
      <p>
        Раздел фото определяет OpenCLIP ViT-B/32 (LAION-400M) по набору текстовых описаний раздела. Он же отсеивает логотипы, афиши, карты,
        марки и портреты. Дубликаты ищутся по перцептивному хэшу и близости эмбеддингов. Кровати, столы и технику на фото общежитий находит
        Ultralytics YOLO11s, обученный на COCO. Описание кампуса пишет Gemini строго по найденным текстам, затем каждое предложение проверяется
        на наличие источника и совпадение чисел.
      </p>
      <h2>Ограничения</h2>
      <p>
        Сервис видит только открытые источники, поэтому у небольших вузов фото может быть мало. Раздел «мало данных» означает нехватку
        снимков, а не отсутствие объекта. Детектор может принять двухъярусную кровать за одну. Веса модели достоверности в текущей версии заданы
        вручную и будут заменены обученными на размеченных фото. Лучше всего сервис работает для вузов, у которых есть страница в Wikidata с
        координатами, сайтом и категорией на Commons.
      </p>
    </DocPage>
  );
}

