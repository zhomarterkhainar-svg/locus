import { useEffect, type ReactNode } from "react";
import { Link } from "react-router-dom";
import { Footer, TopBar } from "../components/Chrome";

function DocPage({ title, updated, children }: { title: string; updated: string; children: ReactNode }) {
  useEffect(() => {
    document.title = `${title} · Candid AI`;
    window.scrollTo(0, 0);
  }, [title]);
  return (
    <>
      <TopBar withSearch />
      <main className="page page--doc">
        <article className="doc">
          <h1>{title}</h1>
          <p className="doc__updated">Редакция от {updated}</p>
          {children}
        </article>
      </main>
      <Footer />
    </>
  );
}

